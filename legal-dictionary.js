// Sorted category names for UI
const LEGAL_CATEGORIES = Object.keys(LEGAL_DICTIONARY);

// Get all terms as flat array
function getAllLegalTerms() {
  const all = [];
  for (const [cat, data] of Object.entries(LEGAL_DICTIONARY)) {
    for (const term of data.terms) {
      all.push({ ...term, category: cat, icon: data.icon });
    }
  }
  return all;
}

// Search legal dictionary
function searchLegalDictionary(query) {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  const all = getAllLegalTerms();
  return all.filter(t =>
    t.tr.toLowerCase().includes(q) ||
    t.en.toLowerCase().includes(q) ||
    t.desc.toLowerCase().includes(q)
  );
}
